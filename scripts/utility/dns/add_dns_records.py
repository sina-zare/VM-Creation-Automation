from scripts.configs import JIRA_TICKET_KEY, DNS_SERVER, PUBLIC_ZONE
import json, os, re, subprocess, sys, tempfile, time, urllib.parse, urllib.request
from scripts.utility.log.logger import get_logger
from scripts.utility.dns.dns_resolver import dns_resolver
import traceback

logger = get_logger("scripts.utility.dns.add_dns_record")

ZONE = PUBLIC_ZONE
ZONE_FILE = "forwardzones/abramad.cloud.dns"
BIND_PATH = "abramad/sysops/bind"
BIND_HOST = "gitlab.abramad.com"
BRANCH = "main"
BEGIN = "; ===== BEGIN AUTO-GENERATED by vm-creation pipeline - do not edit inside this block ====="
END = "; ===== END AUTO-GENERATED ====="


def sh(*cmd, cwd=None):
    return subprocess.run(cmd, cwd=cwd, check=True, text=True,capture_output=True).stdout.strip()


def collect_records(tfvars_path):
    with open(tfvars_path, encoding="utf-8") as f:
        data = json.load(f)
    records = {}
    for vm in data["vms"].values():
        attrs = vm.get("custom_attrs", {})
        url, ip = attrs.get("URL", "").strip(), attrs.get("Public IP", "").strip()
        if not url or not ip:
            continue

        host = urllib.parse.urlparse(url if "//" in url else "//" + url).hostname.lower()
        if not host.endswith("." + ZONE):
            logger.error(
                f"URL host {host} is not inside zone {ZONE}",
                extra={
                    "issue": JIRA_TICKET_KEY,
                }
            )
            raise SystemExit(f"URL host {host} is not inside zone {ZONE}")

        name = host[: -len(ZONE) - 1]
        if not re.fullmatch(r"[a-z0-9]([a-z0-9._-]*[a-z0-9])?", name):
            logger.error(
                f"Invalid record name: {name}",
                extra={
                    "issue": JIRA_TICKET_KEY,
                }
            )
            raise SystemExit(f"Invalid record name: {name}")

        if not re.fullmatch(r"(\d{1,3}\.){3}\d{1,3}", ip):
            logger.error(
                f"Invalid IP: {ip}",
                extra={
                    "issue": JIRA_TICKET_KEY,
                }
            )
            raise SystemExit(f"Invalid IP: {ip}")

        records[name] = ip

    return records


def apply_records(text, records):
    changed = False                                                         # track whether we modified anything
    if BEGIN not in text:                                                   # first run ever: no managed block yet
        text = text.rstrip("\n") + f"\n\n{BEGIN}\n{END}\n"                  # append an empty block

    head, rest = text.split(BEGIN, 1)                                       # before the block / after BEGIN
    block, tail = rest.split(END, 1)                                        # inside the block / after END
    lines = [l for l in block.strip("\n").split("\n") if l.strip()]         # existing managed records

    for name, ip in records.items():                                        # each record we want (name -> IP)
        pat = re.compile(rf"^\s*{re.escape(name)}\s+IN\s+A\s+(\S+)", re.I)  # regex that finds a line for this name

        # if the name is anywhere outside our block, someone manages it by hand: stop
        if any(pat.match(l) for l in head.splitlines() + tail.splitlines()):
            logger.error(
                f"{name} already exists outside the auto-generated block",
                extra={
                    "issue": JIRA_TICKET_KEY,
                }
            )
            raise SystemExit(f"{name} already exists outside the auto-generated block")

        new_line = f"{name:<24}IN      A       {ip}"    # name padded to 24 chars, then the rest
        for i, l in enumerate(lines):                   # look for the name inside our block
            m = pat.match(l)
            if m:                                       # found
                if m.group(1) != ip:                    # different IP: update the line
                    lines[i] = new_line
                    changed = True
                break                                   # correct IP found, so don't append
        else:                                           # loop ended with no break: not found
            lines.append(new_line)                      # add it
            changed = True

    text = head + BEGIN + "\n" + "\n".join(lines) + "\n" + END + tail
    return text, changed


def bump_serial(text):
    pat = re.compile(r"(\d+)\s*;\s*Serial", re.I)
    m = pat.search(text)

    if not m:
        logger.error(
                "Serial not found",
                extra={
                    "issue": JIRA_TICKET_KEY,
                }
            )
        raise SystemExit("Serial not found")

    new = int(m.group(1)) + 1
    if new > 4294967295:
        logger.error(
                "Serial overflow",
                extra={
                    "issue": JIRA_TICKET_KEY,
                }
            )
        raise SystemExit("Serial overflow")

    return text[:m.start(1)] + str(new) + text[m.end(1):]


def api_get(path, token):
    url = f"https://{BIND_HOST}/api/v4/{path}"
    req = urllib.request.Request(url, headers={"PRIVATE-TOKEN": token})
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.load(r)


def wait_for_pipeline(sha, token, appear_timeout=180, run_timeout=900):

    pid = urllib.parse.quote(BIND_PATH, safe="")
    deadline = time.time() + appear_timeout
    pipeline = None

    while time.time() < deadline and not pipeline:
        res = api_get(f"projects/{pid}/pipelines?sha={sha}", token)
        if res:
            pipeline = res[0]
        else:
            time.sleep(5)

    if not pipeline:
        logger.error(
                f"No bind pipeline appeared for commit {sha}",
                extra={
                    "issue": JIRA_TICKET_KEY,
                }
            )
        raise SystemExit(f"No bind pipeline appeared for commit {sha}")


    print(f"Bind pipeline: {pipeline['web_url']}")

    deadline = time.time() + run_timeout
    while time.time() < deadline:
        pipeline = api_get(f"projects/{pid}/pipelines/{pipeline['id']}", token)
        status = pipeline["status"]
        print(f"  status: {status}")
        if status == "success":
            return
        if status in ("failed", "canceled", "skipped"):
            logger.error(
                f"Bind pipeline ended with status {status}: {pipeline['web_url']}",
                extra={
                    "issue": JIRA_TICKET_KEY,
                }
            )
            raise SystemExit(f"Bind pipeline ended with status {status}: {pipeline['web_url']}")

        time.sleep(10)
    
    logger.error(
                "Timed out waiting for bind pipeline",
                extra={
                    "issue": JIRA_TICKET_KEY,
                }
            )
    raise SystemExit("Timed out waiting for bind pipeline")


def main():
    try:
        tfvars, token = sys.argv[1], os.environ["BIND_PUSH_TOKEN"]
        ticket = os.environ.get("JIRA_TICKET_KEY", "unknown")
        records = collect_records(tfvars)
        if not records:
            logger.info(
                    "No URL/Public IP found, nothing to do",
                    extra={
                        "issue": JIRA_TICKET_KEY,
                    }
                )
            print("No URL/Public IP found, nothing to do")
            return

        remote = f"https://oauth2:{token}@{BIND_HOST}/{BIND_PATH}.git"
        workdir = tempfile.mkdtemp()
        sh("git", "clone", "--depth", "1", "-b", BRANCH, remote, workdir)
        sh("git", "config", "user.email", "ci-bot@abramad.com", cwd=workdir)
        sh("git", "config", "user.name", "vm-creation-bot", cwd=workdir)

        sha = None
        for attempt in range(1, 4):
            path = os.path.join(workdir, ZONE_FILE)
            with open(path, encoding="utf-8") as f:
                text = f.read()
            new_text, changed = apply_records(text, records)

            if not changed:
                logger.info(
                    "Records already present, skipping commit",
                    extra={
                        "issue": JIRA_TICKET_KEY,
                        "records": records
                    }
                )
                print("Records already present, skipping commit")
                break

            with open(path, "w", encoding="utf-8", newline="\n") as f:
                f.write(bump_serial(new_text))
            #print(bump_serial(new_text))

            
            sh("git", "commit", "-am", f"dns: add {', '.join(records)} in {ZONE} ({ticket})", cwd=workdir)
            try:
                sh("git", "push", "origin", f"HEAD:{BRANCH}", cwd=workdir)
                sha = sh("git", "rev-parse", "HEAD", cwd=workdir)
                break
            except subprocess.CalledProcessError:
                logger.info(
                    f"Push rejected (attempt {attempt}), resetting and retrying",
                    extra={
                        "issue": JIRA_TICKET_KEY,
                    }
                )
                print(f"Push rejected (attempt {attempt}), resetting and retrying")
                sh("git", "fetch", "origin", BRANCH, cwd=workdir)
                sh("git", "reset", "--hard", f"origin/{BRANCH}", cwd=workdir)
        else:
            logger.error(
                    "Could not push to bind repo",
                    extra={
                        "issue": JIRA_TICKET_KEY,
                    }
                )
            raise SystemExit("Could not push to bind repo")

        if sha:
            wait_for_pipeline(sha, token)

        # ====================================================
        # Second Phase: Check created record by looking it up.
        # ====================================================

        for hostname in records:
            if not dns_resolver(f"{hostname}.{ZONE}", DNS_SERVER): # Returns True/False on name resolution
                logger.error(
                    f"DNS resolution failed for {hostname}",
                    extra={"issue": JIRA_TICKET_KEY}
                )
                sys.exit(1)

    

    except Exception as err:

        error_string_summary = f"{type(err).__name__}: {err}"

        # Get the traceback and extract the last traceback frame
        tb = traceback.extract_tb(err.__traceback__)
        last_call = tb[-1]  # the last traceback frame, where the exception occurred
        error_string_detail = f"Error occurred in line {last_call.lineno}: {last_call.line}"
        print(f"Script failed: {error_string_summary}\n{error_string_detail}")

        logger.error(
            f"add_dns_records() failed",
            extra={
                "issue": JIRA_TICKET_KEY,
                "error_summary": error_string_summary,
                "error_detail": error_string_detail,
            }
        )
        raise    



if __name__ == "__main__":
    main()
